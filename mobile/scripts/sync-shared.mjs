// Single source of truth for logic shared with the website: the GPS engine and the FD/RD maths live in
// ../frontend/lib. This copies them into the app (plain TypeScript, no dependencies) so both always agree.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = ["gps.ts", "deposits.ts"];
mkdirSync(join(root, "src", "lib"), { recursive: true });
for (const f of files) {
  const from = join(root, "..", "frontend", "lib", f);
  const to = join(root, "src", "lib", f);
  if (!existsSync(from)) {
    if (existsSync(to)) { console.log(`sync: ${f} not found next to the app, keeping the existing copy`); continue; }
    throw new Error(`Missing ${from}`);
  }
  const header = `// GENERATED by scripts/sync-shared.mjs from frontend/lib/${f}. Do not edit here; edit the original and run "npm run sync".\n`;
  writeFileSync(to, header + readFileSync(from, "utf8"));
  console.log(`sync: ${f}`);
}
